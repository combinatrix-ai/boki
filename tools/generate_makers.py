"""Generate src/boki/_makers.py: static types for the line makers of the general layouts.

Line makers exist only on entity instances, so type checkers cannot see them on the classes. This script writes one
`typing.Protocol` per maker template, whose `__call__` repeats the create signature exactly, and the classes
`GeneralPL` and `GeneralBS`, which declare one attribute per maker kind of the general layouts. `Entity.pl` and
`Entity.bs` are annotated with them under TYPE_CHECKING. Other layouts fall back to `PL.__getattr__` and
`BS.__getattr__`, which return `LineMaker`.

Usage:
    uv run python tools/generate_makers.py          # rewrite src/boki/_makers.py
    uv run python tools/generate_makers.py --check  # fail if the checked-in file is stale
"""
from __future__ import annotations

import ast
import inspect
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "boki" / "_makers.py"

PROTOCOL_NAMES = {
    "pl_line": "PLLineMaker",
    "income_tax": "IncomeTaxMaker",
    "line": "BSLineMaker",
    "fixed_asset": "FixedAssetMaker",
    "loan": "LoanMaker",
    "construction": "ConstructionMaker",
    "capital": "CapitalMaker",
    "dividend": "DividendMaker",
}

HEADER = '''\
"""Static types of the line makers of the general layouts. Generated by tools/generate_makers.py; do not edit.

`GeneralPL` and `GeneralBS` declare one attribute per maker kind of the IFRS, US GAAP, and J-GAAP general layouts,
typed with the `typing.Protocol` of the maker's template, whose `__call__` repeats the create signature. A kind that
is not declared here (an industry or custom layout) falls back to `PL.__getattr__` or `BS.__getattr__`, which return
`LineMaker`. Nothing imports this module at run time except tests and tools.
"""
from __future__ import annotations

from collections.abc import Iterable
from typing import Protocol

from .ledger import BS, PL, Entity, LineItem
from .series import Series
from .shapes import Kernel
from .units import Quantity


class _MakerMembers(Protocol):
    """What every line maker has besides the call."""

    entity: Entity
    kind: str
    total: Series
    _items: list[LineItem]

    @property
    def items(self) -> list[LineItem]: ...

    @property
    def opening(self) -> Series: ...

    def total_of(self, **filters: object) -> Series: ...
'''


def _literal(value: object) -> str:
    text = json.dumps(value, ensure_ascii=False) if isinstance(value, str) else repr(value)
    if ast.literal_eval(text) != value:
        raise ValueError(f"default {value!r} cannot be written as a literal in the generated module")
    return text


def _parameter(parameter: inspect.Parameter) -> str:
    text = parameter.name
    if parameter.annotation is not inspect.Parameter.empty:
        if not isinstance(parameter.annotation, str):
            raise ValueError(f"{parameter.name}: annotations of create functions must be strings")
        text += f": {parameter.annotation}"
    if parameter.default is not inspect.Parameter.empty:
        text += (" = " if parameter.annotation is not inspect.Parameter.empty else "=") + _literal(parameter.default)
    return text


def _call(signature: inspect.Signature) -> str:
    lines = ["    def __call__(", "        self,"]
    keyword_only_started = False
    for parameter in signature.parameters.values():
        if parameter.kind is inspect.Parameter.KEYWORD_ONLY and not keyword_only_started:
            lines.append("        *,")
            keyword_only_started = True
        elif parameter.kind not in (inspect.Parameter.POSITIONAL_OR_KEYWORD, inspect.Parameter.KEYWORD_ONLY):
            raise ValueError(f"{parameter.name}: unsupported parameter kind {parameter.kind}")
        lines.append(f"        {_parameter(parameter)},")
    returns = signature.return_annotation
    if not isinstance(returns, str):
        raise ValueError("create functions must annotate their return type with a string")
    lines.append(f"    ) -> {returns}: ...")
    return "\n".join(lines)


def collect() -> dict:
    """Template keys, their signatures, and the kinds of the general layouts, read from the runtime makers."""
    sys.path.insert(0, str(ROOT / "src"))
    import boki as b
    from boki._maker_docs import TEMPLATES
    from boki.layouts import Kind

    model = b.Model("Makers", start="2027-01", periods=1, step=b.year)
    general = [model.entity(standard.name, standard=standard) for standard in (b.IFRS, b.USGAAP, b.JGAAP)]
    bank = model.entity("bank", standard=b.IFRS, layout=b.layouts.bank)

    signatures: dict[str, inspect.Signature] = {}
    kinds: dict[str, dict[str, str]] = {"pl": {}, "bs": {}}
    stages: list[str] = []
    for entity in general + [bank]:
        is_general = entity in general
        for namespace, statement, names in (
            ("pl", entity.pl, [k.name for k in entity.layout.pl if isinstance(k, Kind)]),
            ("bs", entity.bs, [k.name for k in entity.layout.bs]),
        ):
            for name in names:
                maker = getattr(statement, name)
                key, signature = maker._template, inspect.signature(maker)
                if signatures.setdefault(key, signature) != signature:
                    raise ValueError(f"template {key!r} is used with different signatures ({entity.layout.name}.{name})")
                known = kinds[namespace].get(name)
                if known is not None and known != key:
                    raise ValueError(
                        f"kind {namespace}.{name} uses template {known!r} in one layout and {key!r} in "
                        f"{entity.layout.name}; GeneralPL and GeneralBS need one type per kind name")
                if is_general or known is not None:
                    kinds[namespace][name] = key
        for stage in entity.layout.stages:
            if stage.name not in stages:
                stages.append(stage.name)
    if set(signatures) != set(TEMPLATES) or set(PROTOCOL_NAMES) != set(TEMPLATES):
        raise ValueError("every template needs a Protocol name and at least one maker in a built-in layout")
    return {"signatures": signatures, "kinds": kinds, "stages": stages, "summaries": {
        key: template.template.splitlines()[0] for key, template in TEMPLATES.items()}}


def render() -> str:
    """The text of src/boki/_makers.py for the current layouts and create signatures."""
    data = collect()
    parts = [HEADER]
    for key, signature in data["signatures"].items():
        summary = data["summaries"][key]
        parts.append(
            f"\n\nclass {PROTOCOL_NAMES[key]}(_MakerMembers, Protocol):\n"
            f'    """{summary}"""\n\n{_call(signature)}\n'
        )
    pl_lines = [f"    {name}: {PROTOCOL_NAMES[key]}" for name, key in data["kinds"]["pl"].items()]
    pl_lines += [f"    {name}: Series" for name in data["stages"]]
    bs_lines = [f"    {name}: {PROTOCOL_NAMES[key]}" for name, key in data["kinds"]["bs"].items()]
    parts.append(
        '\n\nclass GeneralPL(PL):\n    """``co.pl`` of the general layouts: the makers of their PL kinds and their subtotals."""\n\n'
        + "\n".join(pl_lines) + "\n"
    )
    parts.append(
        '\n\nclass GeneralBS(BS):\n    """``co.bs`` of the general layouts: the makers of their balance-sheet kinds."""\n\n'
        + "\n".join(bs_lines) + "\n"
    )
    return "".join(parts)


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale; run: uv run python tools/generate_makers.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
